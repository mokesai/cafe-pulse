// ─── 4. Low confidence: Sam's Club ───────────────────────────────────────────

test.describe("Low confidence — Sam's Club invoice (bulk pricing, clean-text layout)", () => {
  test("parses and either auto-confirms or surfaces low_extraction_confidence exception", async ({ page }) => {
    const uploadRes = await uploadInvoice(page, {
      filePath:      PDF.samclub,
      fileName:      'samclub-invoice.pdf',
      invoiceNumber: `SC-E2E-${Date.now()}`,
      invoiceDate:   '2026-02-28',
    })
    expect(uploadRes.status()).toBe(200)
    const body      = await uploadRes.json() as Record<string, unknown>
    const invoiceId = (body.id ?? (body.data as Record<string, unknown>)?.id) as string

    await page.request.post(`${API_BASE}/invoices/${invoiceId}/parse`)
    const result      = await waitForStatus(page, invoiceId,
      ['parsed', 'matched', 'confirmed', 'pending_exceptions'], 60_000)
    const invoiceData = (result.data ?? result) as Record<string, unknown>

    if (invoiceData.status === 'pending_exceptions') {
      const excRes  = await page.request.get(
        `${API_BASE}/invoice-exceptions?status=open&type=low_extraction_confidence&limit=10`
      )
      const excBody = await excRes.json() as { data: Record<string, unknown>[] }
      const lowConf = excBody.data?.find(e => e.invoice_id === invoiceId)

      if (lowConf) {
        expect(lowConf.exception_type).toBe('low_extraction_confidence')
        const resolveRes = await page.request.post(
          `${API_BASE}/invoice-exceptions/${lowConf.id}/resolve`,
          { data: { action: { type: 'approve_and_continue' }, resolution_notes: 'E2E: low-conf approved' } }
        )
        expect(resolveRes.status()).toBe(200)
      }
    } else {
      expect(['parsed', 'matched', 'confirmed']).toContain(invoiceData.status)
    }
  })
})

