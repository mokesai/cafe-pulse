// ─── Helpers ─────────────────────────────────────────────────────────────────

async function loginAsAdmin(page: import('@playwright/test').Page) {
  const email    = process.env.TEST_ADMIN_EMAIL    ?? 'test-admin@cafe-pulse.test'
  const password = process.env.TEST_ADMIN_PASSWORD ?? 'TestAdmin123!'
  await page.goto(`${BASE_URL}/admin/login`)
  await page.waitForSelector('input[type="email"]', { timeout: 10_000 })
  await page.fill('input[type="email"]', email)
  await page.fill('input[type="password"]', password)
  await page.locator('button[type="submit"], button:has-text("Sign in")').first().click()
  await page.waitForURL(/\/admin\//, { timeout: 20_000 })
}

async function uploadInvoice(
  page: import('@playwright/test').Page,
  opts: {
    filePath: string
    fileName: string
    mimeType?: string
    invoiceNumber?: string
    invoiceDate?: string
    supplierId?: string
  }
) {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const fileBuffer = require('fs').readFileSync(opts.filePath)
  return page.request.post(`${API_BASE}/invoices/upload`, {
    multipart: {
      file: {
        name:     opts.fileName,
        mimeType: opts.mimeType ?? 'application/pdf',
        buffer:   fileBuffer,
      },
      invoice_number: opts.invoiceNumber ?? `INV-E2E-${Date.now()}`,
      invoice_date:   opts.invoiceDate   ?? new Date().toISOString().split('T')[0],
      ...(opts.supplierId ? { supplier_id: opts.supplierId } : {}),
    },
  })
}

async function waitForStatus(
  page: import('@playwright/test').Page,
  invoiceId: string,
  targetStatus: string | string[],
  maxMs = 45_000
): Promise<Record<string, unknown>> {
  const targets  = Array.isArray(targetStatus) ? targetStatus : [targetStatus]
  const deadline = Date.now() + maxMs
  while (Date.now() < deadline) {
    const res = await page.request.get(`${API_BASE}/invoices/${invoiceId}`)
    if (res.status() === 200) {
      const body    = await res.json() as Record<string, unknown>
      const data    = (body.data ?? body) as Record<string, unknown>
      const current = data.status as string
      if (targets.includes(current)) return body
      if (['error', 'failed'].includes(current))
        throw new Error(`Invoice ${invoiceId} hit unexpected status: ${current}`)
    }
    await page.waitForTimeout(1_500)
  }
  throw new Error(`Invoice ${invoiceId} did not reach "${targets.join('|')}" within ${maxMs}ms`)
}

