// ─── 1. Happy path: Bluepoint ─────────────────────────────────────────────────

test.describe('Happy path — Bluepoint invoice (upload → parse → match → confirm)', () => {
  test('full pipeline runs without errors and confirms the invoice', async ({ page }) => {
    const uploadRes = await uploadInvoice(page, {
      filePath:      PDF.bluepoint,
      fileName:      'bluepoint-invoice.pdf',
      invoiceNumber: `BP-E2E-${Date.now()}`,
      invoiceDate:   '2026-03-15',
    })
    expect(uploadRes.status()).toBe(200)
    const uploadBody = await uploadRes.json() as Record<string, unknown>
    expect(uploadBody).toHaveProperty('id')
    const invoiceId = (uploadBody.id ?? (uploadBody.data as Record<string, unknown>)?.id) as string

    // Trigger parse
    const parseRes = await page.request.post(`${API_BASE}/invoices/${invoiceId}/parse`)
    expect([200, 202]).toContain(parseRes.status())

    // Wait for parsed/matched/confirmed
    const parsedBody = await waitForStatus(page, invoiceId, ['parsed', 'matched', 'confirmed'])
    const parsedData = (parsedBody.data ?? parsedBody) as Record<string, unknown>
    expect(['parsed', 'matched', 'confirmed']).toContain(parsedData.status)

    if (parsedData.status === 'confirmed') return // auto-confirmed — done

    // Match to PO
    const matchRes = await page.request.post(`${API_BASE}/invoices/${invoiceId}/match-orders`)
    expect([200, 202]).toContain(matchRes.status())

    // Confirm
    const confirmRes = await page.request.post(`${API_BASE}/invoices/${invoiceId}/confirm`)
    expect(confirmRes.status()).toBe(200)
    const confirmBody = await confirmRes.json() as Record<string, unknown>
    expect(
      (confirmBody.success === true) ||
      (confirmBody.status === 'confirmed')
    ).toBeTruthy()

    // Final verification
    const finalRes  = await page.request.get(`${API_BASE}/invoices/${invoiceId}`)
    const finalBody = await finalRes.json() as Record<string, unknown>
    const finalData = (finalBody.data ?? finalBody) as Record<string, unknown>
    expect(['confirmed', 'matched']).toContain(finalData.status)
  })

  test('invoices list page renders with an upload action', async ({ page }) => {
    await page.goto(`${BASE_URL}/admin/invoices`)
    await page.waitForLoadState('networkidle')
    const uploadBtn  = page.locator('button:has-text("Upload"), button:has-text("Upload Invoice")')
    const emptyState = page.locator('text=/no invoices|upload your first/i')
    await expect(uploadBtn.or(emptyState).first()).toBeVisible({ timeout: 10_000 })
  })
})

// ─── 2. Price variance: Odeko (Cold Brew $12.00 vs PO $11.50) ────────────────

test.describe('Price variance — Odeko invoice (MOK-63 + price delta fixture)', () => {
  test('detects or gracefully handles price variance after parse', async ({ page }) => {
    const uploadRes = await uploadInvoice(page, {
      filePath:      PDF.odeko,
      fileName:      'odeko-invoice.pdf',
      invoiceNumber: `OD-E2E-${Date.now()}`,
      invoiceDate:   '2026-03-24',
    })
    expect(uploadRes.status()).toBe(200)
    const body      = await uploadRes.json() as Record<string, unknown>
    const invoiceId = (body.id ?? (body.data as Record<string, unknown>)?.id) as string

    await page.request.post(`${API_BASE}/invoices/${invoiceId}/parse`)
    await waitForStatus(page, invoiceId, ['parsed', 'matched', 'pending_exceptions', 'confirmed'])
    await page.request.post(`${API_BASE}/invoices/${invoiceId}/match-orders`)

    // Poll up to 15s for a price_variance exception for this invoice
    let varException: Record<string, unknown> | null = null
    const deadline = Date.now() + 15_000
    while (Date.now() < deadline) {
      const excRes = await page.request.get(`${API_BASE}/invoice-exceptions?status=open&limit=20`)
      if (excRes.status() === 200) {
        const excBody = await excRes.json() as { data: Record<string, unknown>[] }
        varException  = excBody.data?.find(
          e => e.invoice_id === invoiceId && e.exception_type === 'price_variance'
        ) ?? null
        if (varException) break
      }
      await page.waitForTimeout(1_500)
    }

    if (varException) {
      expect(varException.exception_type).toBe('price_variance')
      expect(varException.status).toBe('open')

      const resolveRes = await page.request.post(
        `${API_BASE}/invoice-exceptions/${varException.id}/resolve`,
        { data: { action: { type: 'approve_cost_update' }, resolution_notes: 'E2E: variance approved' } }
      )
      expect(resolveRes.status()).toBe(200)
      expect((await resolveRes.json() as Record<string, unknown>).success).toBe(true)

      const detailBody = await (await page.request.get(
        `${API_BASE}/invoice-exceptions/${varException.id}`
      )).json() as { data: Record<string, unknown> }
      expect(detailBody.data?.status).toBe('resolved')
    } else {
      // Variance exceptions require matching PO in staging DB.  Without a PO match,
      // the pipeline completes normally.  Both outcomes are valid.
      const invoiceRes  = await page.request.get(`${API_BASE}/invoices/${invoiceId}`)
      const invoiceBody = await invoiceRes.json() as { data: Record<string, unknown> }
      expect(['parsed', 'matched', 'confirmed', 'pending_exceptions', 'pipeline_running'])
        .toContain(invoiceBody.data?.status)
    }
  })
})

