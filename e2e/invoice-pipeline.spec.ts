// ─── 6. Multi-supplier same Square ID: Walmart + Sam's Club (MOK-63) ──────────

test.describe("Multi-supplier same Square ID — Walmart + Sam's Club coffee (MOK-63)", () => {
  test('inventory endpoint returns items for both suppliers sharing a Square item ID', async ({ page }) => {
    const res  = await page.request.get(`${API_BASE}/inventory?limit=50`)
    expect(res.status()).toBe(200)
    const body = await res.json() as { data: Record<string, unknown>[]; success: boolean }
    expect(body.success).toBe(true)
    expect(Array.isArray(body.data)).toBe(true)

    // Group items by square_item_id → count distinct suppliers
    const bySquareId = new Map<string, Set<string>>()
    for (const item of body.data) {
      const sqId = item.square_item_id as string | null
      if (!sqId) continue
      if (!bySquareId.has(sqId)) bySquareId.set(sqId, new Set())
      bySquareId.get(sqId)!.add(item.supplier_id as string)
    }
    const multiSupplier = [...bySquareId.entries()].filter(([, s]) => s.size > 1)

    if (multiSupplier.length > 0) {
      // MOK-63: multiple suppliers per Square ID — should be returned without DB error
      const [sharedId, suppliers] = multiSupplier[0]
      expect(typeof sharedId).toBe('string')
      expect(suppliers.size).toBeGreaterThanOrEqual(2)
    }
    // If no multi-supplier items yet: inventory endpoint is healthy — test passes
  })
})

// ─── 7. Error path: invalid file ─────────────────────────────────────────────

test.describe('Error path — invalid upload inputs', () => {
  test('uploading a .txt file returns a 4xx error with an error message', async ({ page }) => {
    const res = await page.request.post(`${API_BASE}/invoices/upload`, {
      multipart: {
        file:           { name: 'not-a-pdf.txt', mimeType: 'text/plain', buffer: Buffer.from('not a pdf') },
        invoice_number: `ERR-E2E-${Date.now()}`,
        invoice_date:   new Date().toISOString().split('T')[0],
      },
    })
    expect([400, 415, 422, 413]).toContain(res.status())
    const body      = await res.json() as Record<string, unknown>
    const errorText = (body.error ?? body.message ?? '') as string
    expect(errorText.length).toBeGreaterThan(0)
  })

  test('uploading with missing required fields returns 400', async ({ page }) => {
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const fileBuffer = require('fs').readFileSync(PDF.bluepoint)
    const res = await page.request.post(`${API_BASE}/invoices/upload`, {
      multipart: {
        file: { name: 'bluepoint-invoice.pdf', mimeType: 'application/pdf', buffer: fileBuffer },
        // intentionally omit invoice_number and invoice_date
      },
    })
    expect([400, 422]).toContain(res.status())
    const body      = await res.json() as Record<string, unknown>
    const errorText = (body.error ?? body.message ?? '') as string
    expect(errorText.length).toBeGreaterThan(0)
  })

  test('unauthenticated upload returns 401 or 403', async ({ browser }) => {
    const ctx = await browser.newContext()
    const res = await ctx.request.post(`${API_BASE}/invoices/upload`, {
      multipart: {
        file:           { name: 'test.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4') },
        invoice_number: 'INV-NOAUTH',
        invoice_date:   '2026-03-01',
      },
    })
    expect([401, 403]).toContain(res.status())
    await ctx.close()
  })
})
